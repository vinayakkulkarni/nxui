export function clampValue(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value));
}

/** Luminance test for hex colors; `null` when the color is not hex. */
export function isDarkColor(color: string): boolean | null {
  const match = /^#?([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(color.trim());
  if (!match?.[1]) return null;
  const hex =
    match[1].length === 3
      ? match[1].replace(/./g, (digit) => digit + digit)
      : match[1];
  const [r = 0, g = 0, b = 0] = [0, 2, 4].map(
    (index) => Number.parseInt(hex.slice(index, index + 2), 16) / 255,
  );
  return 0.2126 * r + 0.7152 * g + 0.0722 * b < 0.5;
}

export function hasOrientationPermission(
  value: unknown,
): value is OrientationPermissionApi {
  return (
    typeof value === 'function' &&
    'requestPermission' in value &&
    typeof value.requestPermission === 'function'
  );
}
